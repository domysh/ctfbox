/*
	The control room is not protected by a password: it is protected by the
	network it is reached from. The admin WireGuard profiles generated by
	confgen.py live in 10.80.253.0/24, and WireGuard only accepts a packet whose
	source address matches the AllowedIPs of the peer that signed it. Holding an
	admin profile is therefore what proves you are an organizer, and there is no
	extra secret to leak, rotate or type into a laptop at a competition desk.

	The loopback address is allowed too, so that the organizers can still drive
	the API with `docker exec` on the control node if they lose VPN access.
*/

// adminVPNNetwork is the subnet confgen.py hands to the admin WireGuard
// profiles. It is the only way in, on purpose: there is no token, no password
// and no configurable allow list, so the profile itself is the credential and
// there is nothing else that could be misconfigured into opening the door.
const adminVPNNetwork = "10.80.253.0/24"

var adminNetwork *net.IPNet

func init() {
	_, network, err := net.ParseCIDR(adminVPNNetwork)
	if err != nil {
		panic("invalid admin network: " + err.Error())
	}
	adminNetwork = network
}

// peerIP is the address the request really came from. X-Forwarded-For is
// deliberately ignored: a client can set it, and this is an authorization
// decision.
func peerIP(r *http.Request) net.IP {
	host, _, err := net.SplitHostPort(r.RemoteAddr)
	if err != nil {
		host = r.RemoteAddr
	}
	return net.ParseIP(host)
}

// isAdminRequest has no exception at all, not even for debug builds or for the
// loopback of the game server itself: an organizer is somebody holding an admin
// WireGuard profile, and nothing else. To work on the control room locally,
// connect to the game with one of the profiles in router/configs/admins/.
func isAdminRequest(r *http.Request) bool {
	ip := peerIP(r)
	return ip != nil && adminNetwork.Contains(ip)
}

func adminOnly(next http.HandlerFunc) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		if !isAdminRequest(r) {
			http.Error(w, "The control room is only reachable from an admin VPN profile", http.StatusForbidden)
			return
		}
		next(w, r)
	}
}

// adminActor labels the audit log with the profile the action came from.
func adminActor(r *http.Request) string {
	if ip := peerIP(r); ip != nil {
		return "admin@" + ip.String()
	}
	return "admin"
}

// handleAdminWhoami is the only unauthenticated endpoint: the scoreboard calls
// it to decide whether to show the control room at all.
func handleAdminWhoami(w http.ResponseWriter, r *http.Request) {
	address := ""
	if ip := peerIP(r); ip != nil {
		address = ip.String()
	}
	writeJSON(w, map[string]interface{}{
		"admin": isAdminRequest(r),
		"ip":    address,
	})
}

