type attackEdge struct {
	FromTeam int     `json:"from_team"`
	ToTeam   int     `json:"to_team"`
	Service  string  `json:"service"`
	Flags    int     `json:"flags"`
	Points   float64 `json:"points"`
}

// handleAdminAttackGraph shows who is stealing from whom: the cheapest and most
// reliable "who is attacking" signal available, straight from the submissions.
func handleAdminAttackGraph(w http.ResponseWriter, r *http.Request) {
	type row struct {
		Attacker string  `bun:"attacker"`
		Victim   string  `bun:"victim"`
		Service  string  `bun:"service"`
		Flags    int     `bun:"flags"`
		Points   float64 `bun:"points"`
	}
	rows := make([]row, 0)
	query := conn.NewSelect().Model((*db.FlagSubmission)(nil)).
		ColumnExpr("submit.team AS attacker").
		ColumnExpr("flag.team AS victim").
		ColumnExpr("flag.service AS service").
		ColumnExpr("count(*) AS flags").
		ColumnExpr("coalesce(sum(submit.offensive_points), 0) AS points").
		Join("JOIN flags flag ON flag.id = submit.flag_id").
		GroupExpr("submit.team, flag.team, flag.service")

	if since := r.URL.Query().Get("since_round"); since != "" {
		query = query.Where("submit.round >= ?", since)
	}
	if err := query.Scan(r.Context(), &rows); err != nil {
		log.Errorf("Error building attack graph: %v", err)
		http.Error(w, "Internal server error", http.StatusInternalServerError)
		return
	}
	edges := make([]attackEdge, 0, len(rows))
	for _, entry := range rows {
		edges = append(edges, attackEdge{
			FromTeam: extractTeamID(entry.Attacker),
			ToTeam:   extractTeamID(entry.Victim),
			Service:  entry.Service,
			Flags:    entry.Flags,
			Points:   entry.Points,
		})
	}
	writeJSON(w, edges)
}

