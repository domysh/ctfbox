func handleAdminPatchSettings(w http.ResponseWriter, r *http.Request) {
	var patch settingsPatch
	if err := json.NewDecoder(r.Body).Decode(&patch); err != nil {
		http.Error(w, "Invalid request", http.StatusBadRequest)
		return
	}

	configPatch := map[string]interface{}{}
	changed := make([]string, 0)

	if patch.TickTime != nil && *patch.TickTime > 0 {
		writeSetting(setTickTime, strconv.FormatInt(*patch.TickTime, 10))
		configPatch["tick_time"] = *patch.TickTime
		changed = append(changed, "tick_time")
	}
	if patch.FlagExpireTicks != nil && *patch.FlagExpireTicks > 0 {
		writeSetting(setFlagExpireTicks, strconv.FormatInt(*patch.FlagExpireTicks, 10))
		configPatch["flag_expire_ticks"] = *patch.FlagExpireTicks
		changed = append(changed, "flag_expire_ticks")
	}
	if patch.InitialServiceScore != nil && *patch.InitialServiceScore > 0 {
		writeSetting(setInitialScore, strconv.FormatFloat(*patch.InitialServiceScore, 'f', -1, 64))
		configPatch["initial_service_score"] = *patch.InitialServiceScore
		changed = append(changed, "initial_service_score")
	}
	if patch.MaxFlagsPerRequest != nil && *patch.MaxFlagsPerRequest > 0 {
		writeSetting(setMaxFlags, strconv.Itoa(*patch.MaxFlagsPerRequest))
		configPatch["max_flags_per_request"] = *patch.MaxFlagsPerRequest
		changed = append(changed, "max_flags_per_request")
	}
	if patch.ClearSubmissionTmo {
		writeSetting(setSubmissionTmo, "")
		configPatch["submission_timeout"] = nil
		changed = append(changed, "submission_timeout")
	} else if patch.SubmissionTimeout != nil {
		writeSetting(setSubmissionTmo, strconv.FormatFloat(*patch.SubmissionTimeout, 'f', -1, 64))
		configPatch["submission_timeout"] = *patch.SubmissionTimeout
		changed = append(changed, "submission_timeout")
	}
	if patch.GraceTime != nil && *patch.GraceTime >= 0 {
		writeSetting(setGraceTime, strconv.FormatInt(*patch.GraceTime, 10))
		configPatch["grace_time"] = *patch.GraceTime
		changed = append(changed, "grace_time")
	}
	if patch.CheckerTimeout != nil && *patch.CheckerTimeout > 0 {
		writeSetting(setCheckerTimeout, strconv.FormatInt(*patch.CheckerTimeout, 10))
		configPatch["checker_timeout"] = *patch.CheckerTimeout
		changed = append(changed, "checker_timeout")
	}
	if patch.ClearEndTime {
		writeSetting(setEndTime, "")
		configPatch["end_time"] = nil
		changed = append(changed, "end_time")
	} else if patch.EndTime != nil {
		parsed, err := time.Parse(time.RFC3339, *patch.EndTime)
		if err != nil {
			http.Error(w, "Invalid end_time, expected RFC3339", http.StatusBadRequest)
			return
		}
		writeSetting(setEndTime, parsed.Format(time.RFC3339))
		configPatch["end_time"] = parsed.Format(time.RFC3339)
		changed = append(changed, "end_time")
	}
	if patch.ClearFreezeTime {
		gs.SetScoreboardFreezeAt(nil)
		changed = append(changed, "scoreboard_freeze_time")
	} else if patch.ScoreboardFreezeAt != nil {
		parsed, err := time.Parse(time.RFC3339, *patch.ScoreboardFreezeAt)
		if err != nil {
			http.Error(w, "Invalid scoreboard_freeze_time, expected RFC3339", http.StatusBadRequest)
			return
		}
		gs.SetScoreboardFreezeAt(&parsed)
		changed = append(changed, "scoreboard_freeze_time")
	}

	if len(configPatch) > 0 {
		if err := patchConfigFile(configPatch); err != nil {
			log.Errorf("Error writing config.json: %v", err)
		}
	}
	ReloadState()
	invalidateAllCaches()
	auditLog(adminActor(r), "settings.update", "", strings.Join(changed, ","))
	writeJSON(w, gs.Settings())
}

