func registerAdminRoutes(router *mux.Router) {
	admin := router.PathPrefix("/api/admin").Subrouter()
	get := func(path string, handler http.HandlerFunc) {
		admin.HandleFunc(path, adminOnly(handler)).Methods("GET")
	}
	post := func(path string, handler http.HandlerFunc) {
		admin.HandleFunc(path, adminOnly(handler)).Methods("POST")
	}
	patch := func(path string, handler http.HandlerFunc) {
		admin.HandleFunc(path, adminOnly(handler)).Methods("PATCH")
	}

	router.HandleFunc("/api/admin/whoami", handleAdminWhoami).Methods("GET")

	get("/overview", handleAdminOverview)
	get("/settings", handleAdminGetSettings)
	patch("/settings", handleAdminPatchSettings)
	get("/teams", handleAdminTeams)
	patch("/teams/{team_id}", handleAdminPatchTeam)
	post("/teams/{team_id}/reset-vm", handleAdminResetVM)
	get("/services", handleAdminServices)
	patch("/services/{service}", handleAdminPatchService)
	post("/network/{action}", handleAdminNetwork)
	post("/scoreboard/freeze", handleAdminFreeze)
	post("/game/pause", handleAdminPause)
	post("/reload", handleAdminReload)
	get("/workers", handleAdminWorkers)
	admin.HandleFunc("/workers/{worker_id}", adminOnly(handleAdminDropWorker)).Methods("DELETE")
	get("/jobs", handleAdminJobs)
	get("/attack-graph", handleAdminAttackGraph)
	get("/submissions", handleAdminSubmissions)
	get("/submissions/stats", handleAdminSubmissionStats)
	get("/audit", handleAdminAudit)
	get("/flags", handleAdminFlags)
	get("/traffic", handleAdminTraffic)
	get("/traffic/matrix", handleAdminTrafficMatrix)
	get("/traffic/peers", handleAdminPeerTraffic)
	get("/vpn/profiles", handleAdminVPNProfiles)
	post("/vpn/profiles/{address}/suspend", handleAdminSuspendProfile)
	get("/pcap/status", handleAdminPcapStatus)
	get("/pcap/download", handleAdminPcapDownload)
	post("/announcements", handleAdminCreateAnnouncement)
	admin.HandleFunc("/announcements/{id}", adminOnly(handleAdminDeleteAnnouncement)).Methods("DELETE")
}
