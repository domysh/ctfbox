func handleAdminNetwork(w http.ResponseWriter, r *http.Request) {
	action := mux.Vars(r)["action"]
	var err error
	switch action {
	case "freeze":
		err = CtfRouteFreeze()
	case "lock":
		err = CtfRouteLock()
	case "unlock":
		err = CtfRouteUnlock()
	default:
		http.Error(w, "Unknown action", http.StatusBadRequest)
		return
	}
	auditLog(adminActor(r), "network."+action, "", errText(err))
	if err != nil {
		http.Error(w, err.Error(), http.StatusInternalServerError)
		return
	}
	writeJSON(w, map[string]string{"network_state": gs.NetworkState()})
}

func errText(err error) string {
	if err == nil {
		return "ok"
	}
	return err.Error()
}

func handleAdminFreeze(w http.ResponseWriter, r *http.Request) {
	var req struct {
		Frozen bool    `json:"frozen"`
		Round  *int    `json:"round"`
		At     *string `json:"at"`
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, "Invalid request", http.StatusBadRequest)
		return
	}
	if req.At != nil {
		parsed, err := time.Parse(time.RFC3339, *req.At)
		if err != nil {
			http.Error(w, "Invalid at, expected RFC3339", http.StatusBadRequest)
			return
		}
		gs.SetScoreboardFreezeAt(&parsed)
		auditLog(adminActor(r), "scoreboard.schedule_freeze", "", parsed.Format(time.RFC3339))
		writeJSON(w, gs.Settings())
		return
	}
	round := db.GetExposedRound()
	if req.Round != nil {
		round = *req.Round
	}
	gs.SetScoreboardFreeze(req.Frozen, round)
	if req.Frozen {
		auditLog(adminActor(r), "scoreboard.freeze", "", "round "+strconv.Itoa(round))
	} else {
		auditLog(adminActor(r), "scoreboard.unfreeze", "", "")
	}
	writeJSON(w, gs.Settings())
}

