type teamPatch struct {
	Name          *string `json:"name"`
	Image         *string `json:"image"`
	Nop           *bool   `json:"nop"`
	GameBanned    *bool   `json:"game_banned"`
	NetworkBanned *bool   `json:"network_banned"`
	BanReason     *string `json:"ban_reason"`
	RotateToken   bool    `json:"rotate_token"`
}

func handleAdminPatchTeam(w http.ResponseWriter, r *http.Request) {
	teamID, err := strconv.Atoi(mux.Vars(r)["team_id"])
	if err != nil {
		http.Error(w, "Invalid team id", http.StatusBadRequest)
		return
	}
	current := gs.TeamByID(teamID)
	if current == nil {
		http.Error(w, "Unknown team", http.StatusNotFound)
		return
	}
	var patch teamPatch
	if err := json.NewDecoder(r.Body).Decode(&patch); err != nil {
		http.Error(w, "Invalid request", http.StatusBadRequest)
		return
	}

	ctx := r.Context()
	query := conn.NewUpdate().Model((*db.Team)(nil)).Where("id = ?", teamID).Set("updated_at = ?", time.Now())
	changes := make([]string, 0)

	if patch.Name != nil && strings.TrimSpace(*patch.Name) != "" {
		query = query.Set("name = ?", strings.TrimSpace(*patch.Name))
		changes = append(changes, "name")
	}
	if patch.Image != nil {
		query = query.Set("image = ?", *patch.Image)
		changes = append(changes, "image")
	}
	if patch.Nop != nil {
		query = query.Set("nop = ?", *patch.Nop)
		changes = append(changes, "nop")
	}
	if patch.GameBanned != nil {
		query = query.Set("game_banned = ?", *patch.GameBanned)
		changes = append(changes, "game_banned")
	}
	if patch.BanReason != nil {
		query = query.Set("ban_reason = ?", *patch.BanReason)
		changes = append(changes, "ban_reason")
	}
	newToken := ""
	if patch.RotateToken {
		newToken = genToken()
		query = query.Set("token = ?", newToken)
		changes = append(changes, "token")
	}
	if patch.NetworkBanned != nil {
		query = query.Set("network_banned = ?", *patch.NetworkBanned)
		changes = append(changes, "network_banned")
	}

	if len(changes) == 0 {
		writeJSON(w, current)
		return
	}
	if _, err := query.Exec(ctx); err != nil {
		log.Errorf("Error updating team %v: %v", teamID, err)
		http.Error(w, "Internal server error", http.StatusInternalServerError)
		return
	}

	if patch.NetworkBanned != nil {
		var routeErr error
		if *patch.NetworkBanned {
			routeErr = CtfRouteBanTeam(teamID)
		} else {
			routeErr = CtfRouteUnbanTeam(teamID)
		}
		if routeErr != nil {
			log.Errorf("Error applying network ban on team %v: %v", teamID, routeErr)
		}
	}

	ReloadState()
	invalidateAllCaches()
	syncTeamsToConfigFile()
	auditLog(adminActor(r), "team.update", strconv.Itoa(teamID), strings.Join(changes, ","))
	writeJSON(w, gs.TeamByID(teamID))
}

// syncTeamsToConfigFile mirrors the runtime team list back into config.json so
// that run.py keeps generating the same infrastructure on the next restart.
func syncTeamsToConfigFile() {
	teams := gs.Teams()
	out := make([]map[string]interface{}, 0, len(teams))
	for _, team := range teams {
		out = append(out, map[string]interface{}{
			"id":    team.ID,
			"name":  team.Name,
			"token": team.Token,
			"nop":   team.Nop,
			"image": team.Image,
		})
	}
	if err := patchConfigFile(map[string]interface{}{"teams": out}); err != nil {
		log.Errorf("Error writing teams to config.json: %v", err)
	}
}

func genToken() string {
	const alphabet = "0123456789abcdef"
	randLock.Lock()
	defer randLock.Unlock()
	out := make([]byte, 64)
	for i := range out {
		out[i] = alphabet[randSrc.Intn(len(alphabet))]
	}
	return string(out)
}

